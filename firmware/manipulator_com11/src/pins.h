#pragma once

// План распиновки ESP32 для manipulator_com11 (board = esp32dev)
// Цели:
// 1) Не использовать чувствительные пины без необходимости.
// 2) Сгруппировать пины по функциям.
// 3) Оставить исторические имена PIN_RS485_* для бывшей межплатной линии,
//    теперь она используется как локальная I2C-шина статуса.

// =========================
// Локальная шина статуса (исторические имена PIN_RS485_* сохранены)
// =========================
#define PIN_RS485_RX       16  // SDA I2C status bus
#define PIN_RS485_TX       17  // SCL I2C status bus
#define PIN_RS485_DE_RE    13  // резерв / бывший DE+RE

// =========================
// Шаговый привод DM556
// =========================
#define STEP_PIN           18  // STEP: импульсы шага на драйвер
#define DIR_PIN            21  // DIR: направление вращения
#define ENABLE_PIN         19  // ENA: разрешение драйвера (активный LOW)
#define ALM_PIN            23  // ALM: авария драйвера (вход)

// =========================
// Реле (контур сброса питания драйвера)
// =========================
#define RELAY_PIN          22  // Управление реле

// =========================
// Выходы пневматики
// =========================
#define GRIP_SOL_PIN       25  // Соленоид захвата (открыть/закрыть)
#define Z_SOL_PIN          26  // Соленоид оси Z (вверх/вниз)

// =========================
// Входы датчиков
// =========================
// ВАЖНО: GPIO34/35 только вход, внутренней подтяжки нет.
// Для этих линий нужны внешние подтягивающие резисторы (например, 10 кОм к 3.3V).
#define LIMIT_SWITCH_LEFT  34  // Левый концевик горизонтального хода
#define LIMIT_SWITCH_RIGHT 35  // Правый концевик горизонтального хода
#define GRIP_OPEN_SW       32  // Датчик "захват открыт"
#define GRIP_CLOSED_SW     33  // Датчик "захват закрыт"
#define Z_UP_SW            27  // Датчик "ось Z в верхнем положении"
#define Z_DOWN_SW          14  // Датчик "ось Z в нижнем положении"

// =========================
// Пины, которые лучше не занимать
// =========================
// GPIO6..11   - подключены к встроенной SPI Flash.
// GPIO1, GPIO3 - UART0 (прошивка и лог по USB).
// GPIO0,2,4,5,12,15 - strapping-пины (влияют на загрузку ESP32).

// =========================
// Свободные пины для manipulator_com11
// =========================
// Фактически заняты в коде: GPIO13, GPIO14, GPIO16, GPIO17, GPIO18, GPIO19,
// GPIO21, GPIO22, GPIO23, GPIO25, GPIO26, GPIO27, GPIO32, GPIO33, GPIO34, GPIO35.
// Свободные сейчас:
// - Универсальные (вход/выход) из безопасного набора: нет.
//   Применение: для новых выходов нужен перенос текущих линий, расширитель GPIO
//   или аккуратное использование strapping-пинов.
// - Только вход: GPIO36, GPIO39.
//   Применение: дополнительные датчики/концевики/герконы.
// Условно свободные, но с ограничениями:
// - GPIO1 и GPIO3: UART0, лучше не занимать.
// - GPIO2, GPIO4, GPIO5, GPIO12, GPIO15: использовать только с учетом
//   требований к уровням на старте (strapping).
