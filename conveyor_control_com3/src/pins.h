constexpr uint8_t PIN_RELAY_2 = 22;         // Канал реле 2

// Дополнительные датчики
// GPIO34/35/36/39 только вход, внутренней подтяжки нет.
constexpr uint8_t PIN_SENSOR_EXT_1 = 34;    // Внешний датчик 1 (только вход)
constexpr uint8_t PIN_SENSOR_EXT_2 = 35;    // Внешний датчик 2 (только вход)
constexpr uint8_t PIN_SENSOR_EXT_3 = 36;    // Внешний датчик 3 (только вход)
constexpr uint8_t PIN_SENSOR_EXT_4 = 39;    // Внешний датчик 4 (только вход)

