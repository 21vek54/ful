// =========================
// Рабочие пины (используются в этой прошивке)
// =========================

// Основной конвейер
constexpr uint8_t PIN_STEP_PUL = 13;        // Импульсы STEP драйвера DM542

// Каретка сдвига
constexpr uint8_t PIN_SHIFT_DIR = 14;       // Направление каретки сдвига
constexpr uint8_t PIN_SHIFT_PUL = 23;       // Импульсы STEP каретки сдвига
constexpr uint8_t PIN_SHIFT_SENSOR_Z = 33;  // Геркон, край Z
constexpr uint8_t PIN_SHIFT_SENSOR_C = 25;  // Геркон, край C

// Пневматика и датчики
constexpr uint8_t PIN_FLAG = 27;            // Пневмоцилиндр флага
constexpr uint8_t PIN_SENSOR = 26;          // Щелевой датчик

// Позиционный конвейер (двухручейковый)
constexpr uint8_t PIN_POS_PUL = 32;         // Импульсы STEP драйвера EVA25

// Отводная группа
constexpr uint8_t PIN_STEP2_PUL = 19;       // Импульсы STEP двухручейкового отвода
constexpr uint8_t PIN_RELAY_1 = 21;         // Реле пуска основного отвода / частотника

// Запайщик
constexpr uint8_t PIN_RELAY_2 = 22;         // Реле старта запайщика
constexpr uint8_t PIN_SENSOR_EXT_1 = 34;    // Вход "цикл запайки завершен"

// Локальная шина статуса (исторические имена сохранены для совместимости кода)
constexpr uint8_t PIN_RS485_RX = 16;        // SDA I2C status bus
constexpr uint8_t PIN_RS485_TX = 17;        // SCL I2C status bus
constexpr uint8_t PIN_RS485_DE_RE = 18;     // резерв / бывший DE+RE

// Дополнительные входы резерва
// GPIO34/35/36/39 только вход, внутренней подтяжки нет.
constexpr uint8_t PIN_SENSOR_EXT_2 = 35;    // Резервный вход 2 (только вход)
constexpr uint8_t PIN_SENSOR_EXT_3 = 36;    // Резервный вход 3 (только вход)
constexpr uint8_t PIN_SENSOR_EXT_4 = 39;    // Резервный вход 4 (только вход)

// =========================
// Пины, которые лучше не занимать
// =========================
// GPIO6..11   - подключены к встроенной SPI Flash.
// GPIO1, GPIO3 - UART0 (прошивка и лог по USB).
// GPIO0,2,4,5,12,15 - strapping-пины (влияют на загрузку ESP32).

// =========================
// Свободные пины для conveyor_control_com10
// =========================
// Фактически заняты в коде: 13,14,16,17,18,19,21,22,23,25,26,27,32,33,34.
// Реально свободные сейчас:
// - Только вход: GPIO35, GPIO36, GPIO39.
//   Применение: концевики, герконы, оптодатчики, дискретные входы.
// - Универсальных свободных GPIO без конфликта с текущей логикой сейчас нет.
// Условно свободные, но с ограничениями:
// - GPIO1 и GPIO3: UART0, прошивка и лог, лучше не занимать.
// - GPIO2, GPIO4, GPIO5, GPIO12, GPIO15: использовать только с учетом
//   требований к уровням на старте (strapping).
