#pragma once

#include <Arduino.h>

// =========================
// Рабочие пины (используются в master_control_com12)
// =========================

// RS485 (UART2) для Modbus RTU
constexpr uint8_t PIN_RS485_RX = 16;        // RO трансивера -> RX ESP32
constexpr uint8_t PIN_RS485_TX = 17;        // DI трансивера <- TX ESP32
constexpr uint8_t PIN_RS485_DE_RE = 18;     // DE+RE, управление направлением

// =========================
// Пины, которые лучше не занимать
// =========================
// GPIO6..11   - подключены к встроенной SPI Flash.
// GPIO1, GPIO3 - UART0 (прошивка и лог по USB).
// GPIO0,2,4,5,12,15 - strapping-пины (влияют на загрузку ESP32).

// =========================
// Свободные пины для master_control_com12
// =========================
// Фактически заняты в коде: GPIO16, GPIO17, GPIO18.
// Свободные сейчас:
// - Универсальные (вход/выход):
//   GPIO13, GPIO14, GPIO19, GPIO21, GPIO22, GPIO23, GPIO25, GPIO26,
//   GPIO27, GPIO32, GPIO33.
//   Применение: реле, световая индикация, соленоиды, дискретные команды,
//   STEP/DIR/EN для драйверов, интерфейсные сигналы.
// - Только вход: GPIO34, GPIO35, GPIO36, GPIO39.
//   Применение: концевики, герконы, оптодатчики, аварийные входы.
// Условно свободные, но с ограничениями:
// - GPIO1 и GPIO3: UART0, лучше не занимать.
// - GPIO2, GPIO4, GPIO5, GPIO12, GPIO15: использовать только с учетом
//   требований к уровням на старте (strapping).
